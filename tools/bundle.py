#!/usr/bin/env python3
"""Create a compact, text-only bundle of the Cleanup project source.

Run from anywhere:
    python tools/bundle.py

The output is written to the repository root as bundle.txt. Large generated
results and diagnostic evidence are deliberately excluded.
"""
from __future__ import annotations

import os
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "bundle.txt"

INCLUDE = [
    "yolo_mask_auto_select.py",
    "yolo_mask_auto_select_modules",
    "yolo_mask_routing_audit.py",
    "label_tool.py",
    "train_ranker.py",
    "build_final_picks.py",
    "scripts",
    "README.md",
    "PROJECT_HANDOFF.md",
    "requirements-before-iopaint.txt",
]

EXTENSIONS = {".py", ".md", ".txt", ".json", ".toml", ".yaml", ".yml"}
SKIP_DIRS = {
    ".git",
    ".venv",
    "venv",
    "env",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    "node_modules",
    "fixtures",
    "diagnostics",
    "yolo_mask_winners",
    "output",
    "outputs",
}


def iter_source_files(directory: Path):
    """Yield supported files, pruning generated or data-heavy directories."""
    for current, dirnames, filenames in os.walk(
        directory, topdown=True, followlinks=False
    ):
        current_path = Path(current)
        dirnames[:] = sorted(
            name
            for name in dirnames
            if name not in SKIP_DIRS
            and not (current_path / name).is_symlink()
        )
        for filename in sorted(filenames):
            path = current_path / filename
            if path.is_symlink() or not path.is_file():
                continue
            if path.suffix.lower() in EXTENSIONS:
                yield path


def collect_files() -> tuple[list[Path], list[str]]:
    """Collect the configured project files in a stable, duplicate-free order."""
    files: list[Path] = []
    missing: list[str] = []
    seen: set[Path] = set()

    for item in INCLUDE:
        path = ROOT / item
        if not path.exists():
            missing.append(item)
            continue

        candidates = [path] if path.is_file() else iter_source_files(path)
        for candidate in candidates:
            resolved = candidate.resolve()
            if resolved in seen or candidate.is_symlink():
                continue
            if candidate.suffix.lower() not in EXTENSIONS:
                continue
            seen.add(resolved)
            files.append(candidate)

    return sorted(files, key=lambda file: file.relative_to(ROOT).as_posix()), missing


def build_bundle(files: list[Path], missing: list[str]) -> str:
    lines = [
        "# CLEANUP PROJECT BUNDLE",
        "",
        "Generated by tools/bundle.py.",
        "This bundle contains project source, tests, scripts, and documentation.",
        "Generated result images, yolo_mask_winners/, diagnostics/, caches, and",
        "virtual environments are intentionally excluded.",
        "",
        "## File list",
        "",
    ]
    lines.extend(f"- {path.relative_to(ROOT).as_posix()}" for path in files)

    if missing:
        lines.extend(["", "## Configured paths not found", ""])
        lines.extend(f"- {item}" for item in missing)

    for path in files:
        relative = path.relative_to(ROOT).as_posix()
        try:
            content = path.read_text(encoding="utf-8", errors="replace")
        except OSError as exc:
            raise RuntimeError(f"Could not read {relative}: {exc}") from exc
        lines.extend(
            [
                "",
                "",
                f"===== {relative} =====",
                "",
                content.rstrip(),
            ]
        )

    return "\n".join(lines) + "\n"


def main() -> int:
    files, missing = collect_files()
    if not files:
        raise RuntimeError("No project files were found; bundle.txt was not written.")

    content = build_bundle(files, missing)
    temporary_output = OUTPUT.with_name(OUTPUT.name + ".tmp")
    temporary_output.write_text(content, encoding="utf-8")
    temporary_output.replace(OUTPUT)

    print(f"{len(files)} files -> {OUTPUT.relative_to(ROOT)}")
    if missing:
        print("Configured paths not found: " + ", ".join(missing))
    print(
        "Excluded generated results and diagnostics: "
        "yolo_mask_winners/, diagnostics/, caches, and virtual environments."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
